# Package the Iter mod for a game test.
# Dev-only files (dev/, .git/, dist/) are excluded.
# The user copies dist/Iter into the game; this script never touches the game.

$ErrorActionPreference = 'Stop'
$RepoRoot = (Resolve-Path (Join-Path $PSScriptRoot '..')).Path
$DistRoot = Join-Path $RepoRoot 'dist'
$Dest = Join-Path $DistRoot 'Iter'
$Marker = Join-Path $Dest '.iter-build'

if (Test-Path $Dest) {
    if (-not (Test-Path $Marker)) {
        throw "Refusing to delete $Dest because it has no .iter-build marker. Move it to _archive or remove it manually."
    }
    Remove-Item -LiteralPath $Dest -Recurse -Force
}

New-Item -ItemType Directory -Force $Dest | Out-Null

$commit = (& git -C $RepoRoot rev-parse --short HEAD 2>$null)
if (-not $commit) { $commit = 'unknown' }
$markerText = @(
    'Generated by dev/build.ps1',
    ('commit: ' + $commit),
    ('built: ' + (Get-Date).ToString('u'))
) -join "`n"
Set-Content -LiteralPath $Marker -Value $markerText -Encoding utf8

$items = @('mod.txt', 'tdlq.dds', 'loc', 'lua', 'menu', 'changelog.txt', 'MENU_OPTIONS.md', 'README.md')
foreach ($item in $items) {
    $source = Join-Path $RepoRoot $item
    if (-not (Test-Path -LiteralPath $source)) {
        throw "Missing runtime item: $item"
    }
    Copy-Item -LiteralPath $source -Destination $Dest -Recurse -Force
}

Write-Host "built $Dest"
Write-Host "commit: $commit"
Write-Host ''
Write-Host 'Copy to the game (user action):'
Write-Host ('  Copy-Item -LiteralPath ''{0}'' -Destination ''C:\Program Files (x86)\Steam\steamapps\common\PAYDAY 2\mods\Iter'' -Recurse -Force' -f $Dest)
Write-Host ''
Write-Host 'Optional test harness (live folder name is test-harness):'
Write-Host ('  Copy-Item -LiteralPath ''{0}'' -Destination ''C:\Program Files (x86)\Steam\steamapps\common\PAYDAY 2\mods\test-harness'' -Recurse -Force' -f (Join-Path $RepoRoot 'dev\test-harness'))
Write-Host '  (do not also keep a second harness copy: two instances double every !iter reply)'
